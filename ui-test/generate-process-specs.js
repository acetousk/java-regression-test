const fs = require('node:fs');
const path = require('node:path');
const { docs, loadProcess } = require('./process-plan');

let documents = 0, activities = 0;
for (const group of ['process-library', 'walkthroughs']) {
  for (const file of fs.readdirSync(path.join(docs, group)).filter(file => file.endsWith('.md')).sort()) {
    const relative = `${group}/${file}`;
    const process = loadProcess(relative);
    const destination = path.join(__dirname, 'docs/business-process', group, file.replace(/\.md$/, '.visual.spec.js'));
    const content = '// Generated by generate-process-specs.js; execution lives in process-runner.js.\n' +
      "const { registerProcess } = require('../../../process-runner');\n" +
      `registerProcess(${JSON.stringify(relative)});\n`;
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    if (fs.existsSync(destination) && !fs.readFileSync(destination, 'utf8').startsWith('// Generated by generate-process-specs.js;')) {
      throw new Error(`Refusing to overwrite hand-written spec: ${destination}`);
    }
    fs.writeFileSync(destination, content);
    documents++;
    activities += process.activities.length;
  }
}
console.log(`Generated ${documents} process specs; ${activities} activity placeholders across 3 render modes.`);
